r"""
For each case and each of the 8 alternative validity indices, reports the
ORACLE-best perplexity (t-SNE) and n_neighbors (UMAP) -- the parameter
value that maximizes the MEAN Spearman rho with ACC, averaged across every
(clustering_method, dataset) pair in that case. This is a companion to
generate_oracle_landscape_plots.py (same underlying aggregation) and to
best_params_by_case_and_index.csv (same numbers, tabular form here
instead) -- NOT a modification of manifold_tsne_umap_summary.tex /
manifold_tsne_umap_averages.tex, which report Algorithm-1-selected values
per DATASET, not case-level oracle values.

IMPORTANT: this is the case-level ORACLE choice (best parameter GIVEN
knowledge of ACC, averaged over all datasets in the case) -- not what
Algorithm 1 would actually select from data alone, and not necessarily a
good choice for any one specific dataset within the case (the case
average can mask substantial per-dataset disagreement).

Run this LOCALLY after retrieving data/ from the cluster and (for Case 4)
running merge_manifold_case4_results.py:

    python generate_best_params_tex.py

Writes tables/best_params_by_case_and_index.tex. Compile with:
    cd tables && pdflatex best_params_by_case_and_index.tex
"""

import os

from generate_oracle_landscape_plots import load_results, aggregate_curves, CASES, INDEX_NAMES

OUT_DIR = 'tables'
os.makedirs(OUT_DIR, exist_ok=True)

METHOD_LABELS = {
    'VRC': 'VRC', 'WG': 'WG', 'WB': 'WB', 'DBCV': 'DBCV', 'CVDD': 'CVDD',
    'VIASCKDE': 'VIASCKDE', 'DCSI': 'DCSI', 'DB': 'DB',
}


def best_param(agg, idx):
    if idx not in agg or not agg[idx]:
        return None, None, None
    best_x = max(agg[idx], key=lambda x: agg[idx][x][0])
    best_rho, n = agg[idx][best_x]
    return best_x, best_rho, n


def to_latex_table(case_tag, case_title, agg_p, agg_k):
    rows = []
    for idx in INDEX_NAMES:
        bp, bpr, np_ = best_param(agg_p, idx)
        bk, bkr, nk = best_param(agg_k, idx)
        rows.append((idx, bp, bpr, np_, bk, bkr, nk))

    finite_p = [r[2] for r in rows if r[2] is not None]
    finite_k = [r[5] for r in rows if r[5] is not None]
    max_p_rho = max(finite_p) if finite_p else None
    max_k_rho = max(finite_k) if finite_k else None

    lines = []
    lines.append(r'\begin{table}[h]')
    lines.append(r'\centering')
    lines.append(
        rf"\caption{{Oracle-best perplexity/$n_{{neighbors}}$ per index, {case_title} "
        rf"-- the parameter value maximizing the MEAN Spearman $\rho$ with ACC, "
        rf"averaged across every (clustering method, dataset) pair in this case. "
        rf"Bold marks the index with the single highest achievable mean $\rho$ in "
        rf"each column (t-SNE / UMAP separately). $n$ = number of (method, dataset) "
        rf"pairs contributing at that parameter value.}}"
    )
    lines.append(r'\begin{tabular}{lcccccc}')
    lines.append(r'\hline')
    lines.append(r'Index & Best perplexity & mean $\rho$ (t-SNE) & $n$ & Best $n_{neighbors}$ & mean $\rho$ (UMAP) & $n$ \\')
    lines.append(r'\hline')
    for idx, bp, bpr, np_, bk, bkr, nk in rows:
        bp_s = str(bp) if bp is not None else '--'
        np_s = str(np_) if np_ is not None else '--'
        bk_s = str(bk) if bk is not None else '--'
        nk_s = str(nk) if nk is not None else '--'
        if bpr is None:
            bpr_s = '--'
        elif max_p_rho is not None and abs(bpr - max_p_rho) < 1e-9:
            bpr_s = rf'\textbf{{{bpr:+.3f}}}'
        else:
            bpr_s = f'{bpr:+.3f}'
        if bkr is None:
            bkr_s = '--'
        elif max_k_rho is not None and abs(bkr - max_k_rho) < 1e-9:
            bkr_s = rf'\textbf{{{bkr:+.3f}}}'
        else:
            bkr_s = f'{bkr:+.3f}'
        lines.append(f'{METHOD_LABELS[idx]} & {bp_s} & {bpr_s} & {np_s} & {bk_s} & {bkr_s} & {nk_s} \\\\')
    lines.append(r'\hline')
    lines.append(r'\end{tabular}')
    lines.append(rf'\label{{tab:best_params_{case_tag}}}')
    lines.append(r'\end{table}')
    return '\n'.join(lines) + '\n'


DOC_PREAMBLE = r"""\documentclass[11pt]{article}
\usepackage[margin=1in]{geometry}
\usepackage{booktabs}
\usepackage{amsmath}

\title{Oracle-Best Perplexity / $n_{neighbors}$ per Case and Index\\
\large (auto-generated by generate\_best\_params\_tex.py -- do not edit by hand)}
\author{}
\date{}

\begin{document}
\maketitle

\section*{What this reports}

For each case and each of the 8 alternative internal validity indices
(VRC, WG, WB, DBCV, CVDD, VIASCKDE, DCSI, DB), this reports the
ORACLE-best perplexity (for the t-SNE representation) and $n_{neighbors}$
(for the UMAP representation) -- i.e.\ the single parameter value that
maximizes the MEAN Spearman $\rho$ with ACC, averaged across every
(clustering method, dataset) pair within that case. This is computed
directly from the already-saved per-parameter sensitivity curves (the
same data underlying \texttt{generate\_oracle\_landscape\_plots.py}'s
landscape figures) -- no re-running of any cluster job.

\textbf{This is NOT the same as Algorithm~1's actual selection.} Algorithm
1 (used throughout the rest of this project, including for $r^*$ and for
the tuned-embedding sibling packages) selects a parameter per INDIVIDUAL
DATASET, using only that dataset's own $K$-curve shape -- it never looks
at ACC. The oracle values here instead assume perfect knowledge of ACC and
average over an entire CASE's worth of datasets at once, so they answer a
different question: ``does a good parameter choice exist at all, in
principle, for this index on this case's data'' -- not ``can Algorithm 1
find it from a single dataset's own curve shape.'' The oracle-best
parameter for a case is not necessarily a good choice for any one
specific dataset within it; a high case-level mean can still hide
substantial disagreement between individual datasets (see the landscape
plots in \texttt{figures/oracle\_landscape/} for the full per-parameter
curves this table's numbers are extracted from).

"""

DOC_CLOSING = r"""\end{document}
"""


def main():
    parts = [DOC_PREAMBLE]

    for case in CASES:
        results = load_results(case['path'])
        parts.append(f"\\section{{{case['title']}}}\n")
        if results is None:
            parts.append(f"No sensitivity data file found at \\texttt{{{case['path'].replace('_', r'\_')}}} -- skipping.\n\n")
            print(f"{case['tag']}: NO DATA -- skipped")
            continue

        agg_p = aggregate_curves(results, 'perplexity')
        agg_k = aggregate_curves(results, 'n_neighbors')
        parts.append(to_latex_table(case['tag'], case['title'], agg_p, agg_k))
        parts.append('')
        n_p = sum(1 for idx in INDEX_NAMES if idx in agg_p)
        n_k = sum(1 for idx in INDEX_NAMES if idx in agg_k)
        print(f"{case['tag']}: table written ({n_p}/{len(INDEX_NAMES)} perplexity indices, {n_k}/{len(INDEX_NAMES)} n_neighbors indices)")

    parts.append(DOC_CLOSING)
    combined = '\n'.join(parts)
    combined_path = os.path.join(OUT_DIR, 'best_params_by_case_and_index.tex')
    with open(combined_path, 'w') as f:
        f.write(combined)
    print(f'\nWrote: {combined_path}')
    print('Compile with:')
    print('  cd tables && pdflatex best_params_by_case_and_index.tex')


if __name__ == '__main__':
    main()
